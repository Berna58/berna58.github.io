const dictionaries: Record<Locale, Dict> = { pt, en };
export type UiKey = keyof Dict;

export function useT(locale: Locale) {
  const dict = dictionaries[locale];
  return <K extends UiKey>(key: K): Dict[K] => dict[key];
}

const monthFormat = {
  pt: new Intl.DateTimeFormat('pt-PT', { month: 'short', timeZone: 'UTC' }),
  en: new Intl.DateTimeFormat('en-GB', { month: 'short', timeZone: 'UTC' }),
};

/** "2024-05" → "mai. 2024" / "May 2024"; "2022" → "2022". */
export function formatYearMonth(value: string, locale: Locale): string {
  const [year, month] = value.split('-');
  if (!month) return year;
  const name = monthFormat[locale].format(new Date(Date.UTC(Number(year), Number(month) - 1, 1)));
  return `${name} ${year}`;
}
